import assert from 'node:assert/strict';
import {orderHealth,requirementHealth,roastPlanHealth,statusSummary} from '../static/status-view.js';
import {routeForHash,mainPages,settingsTabs} from '../static/navigation.js';
import {planPage} from '../static/plan-view.js';
const clock='2026-11-09T03:00:00Z',past='2026-11-09T02:59:59Z',future='2026-11-10T03:00:00Z';
const line={id:'l1',kind:'coffee',unfulfilled:1,status:'Packed / allocated',allocations:[],required_mg:150000,title:'Coffee'};
const order={id:'o1',number:'#1',source:'shopify',due_at:future,fulfillment:'UNFULFILLED',lines:[line]};
const S={clock,orders:[order],fulfillments:[],planner:{rows:[]}};
const tone=o=>orderHealth({...order,...o},S).tone;
assert.equal(tone({}),'green');
assert.equal(tone({due_at:clock}),'green','the deadline itself is not yet overdue');
assert.equal(tone({due_at:past}),'red');
assert.equal(tone({due_at:null}),'yellow');assert.equal(tone({due_at:'invalid'}),'yellow');
assert.equal(tone({due_at:past,fulfillment:'FULFILLED'}),'green','a fulfilled order never becomes overdue');
assert.equal(tone({due_at:past,lines:[{...line,unfulfilled:0}]}),'green');
assert.equal(tone({due_at:past,cancelled:1}),'yellow','cancelled orders are not active overdue commitments');
assert.equal(tone({due_at:past,closed_at:clock}),'yellow','archived but incomplete orders need review');
assert.equal(tone({due_at:past,wholesale:{status:'DRAFT'}}),'yellow');
for(const status of ['Needs mapping','Needs deadline','Allocation at risk','Review split-bag allocations','Awaiting payment'])assert.equal(tone({lines:[{...line,status}]}),'yellow',status);
for(const status of ['Resting','Ready to pack','Packed / allocated'])assert.equal(tone({lines:[{...line,status}]}),'green',status+' can still be on time');
assert.equal(tone({lines:[{...line,status:'Needs allocation / roasting'}]}),'yellow');
const covered={id:'l1',type:'line_id',due_at:future,shortage_mg:0,warnings:[],allocations:[{kind:'planned',batch:'Plan p10000'}]};
S.planner.rows=[covered];S.plans=[{id:'p10000',status:'planned',roast_at:future}];
assert.equal(tone({lines:[{...line,status:'Needs allocation / roasting'}]}),'green','dated planned supply counts as coverage');
S.plans[0].roast_at=past;assert.equal(tone({lines:[{...line,status:'Needs allocation / roasting'}]}),'yellow','late approved roast is not on track');
S.plans[0].roast_at=future;
assert.equal(requirementHealth({...covered,allocations:[{kind:'planned',batch:'Suggestion carryover'}]},S).tone,'yellow','unapproved suggestion is not a firm commitment');
S.planner.rows=[{...covered,warnings:['Configure dispatch rest policy']}];
assert.equal(tone({lines:[{...line,status:'Needs allocation / roasting'}]}),'yellow');
S.fulfillments=[{order_id:order.id}];
assert.equal(tone({fulfillment:'FULFILLED'}),'yellow','confirmed shipment still needs a physical pick');
assert.equal(tone({due_at:past}),'red','an overdue partial shipment still takes priority over a missing pick');
S.fulfillments=[];S.planner.rows=[covered];
assert.equal(requirementHealth({...covered,type:'demand_id',due_at:past},S).tone,'green','covered forecasts do not become short when their roast-by time passes');
S.orders=[{...order,due_at:past}];
assert.equal(requirementHealth(covered,S).tone,'red','covered order is still overdue until dispatched');
S.orders=[order];
assert.equal(requirementHealth({...covered,shortage_mg:100,latest_roast_at:past},S).tone,'red');
assert.equal(requirementHealth({...covered,shortage_mg:100,latest_roast_at:future},S).tone,'yellow');
assert.equal(requirementHealth({...covered,shortage_mg:0,latest_roast_at:past},S).tone,'green');
assert.equal(requirementHealth({...covered,warnings:['Recipe missing']},S).tone,'yellow');
assert.equal(roastPlanHealth({roast_at:past},clock).tone,'red');
assert.equal(roastPlanHealth({roast_at:future},clock).tone,'green');
assert.equal(roastPlanHealth({roast_at:null},clock).tone,'yellow');
assert.equal(mainPages.includes('products'),false);
assert.equal(settingsTabs.products,'Products & POS');
assert.deepEqual(routeForHash('#products'),{view:'settings',tab:'products',hash:'#settings/products'});
assert.equal(routeForHash('#settings/products').tab,'products');
assert.equal(routeForHash('#settings/products').view,'settings');
assert.equal(routeForHash('#settings/coffees','products').tab,'coffees');
assert.equal(routeForHash('#settings','products').tab,'products');
assert.equal(routeForHash('#unknown').view,'today');
assert.equal(routeForHash('#batches/example-id').detail,'example-id');
const esc=s=>String(s??'').replaceAll('<','&lt;').replaceAll('>','&gt;');
assert(!statusSummary({label:'<script>',reason:'<img>'},esc).includes('<script>'));
const h={esc,heading:()=>'',notice:s=>s,kg:n=>n/1e6+' kg',grams:n=>n/1e3+' g',date:s=>s||'Not set',badge:(s)=>s,empty:s=>s,btn:(s,a)=>`<button data-action="${a}">${s}</button>`};
const row={...covered,coffee:'Coffee',profile:'Filter',label:'#1',channel:'dispatch',quantity_mg:150000,covered_mg:150000,charges_mg:[],roast_slots:[],yield_bp:8500,yield_source:'configured estimate',excess_mg:0};
const viewS={...S,settings:{roast_days:[0],charge_mg:1200000},planner:{issues:[],rows:[row]},plans:[{id:'p10000',status:'planned',coffee:'Coffee',roast_at:future,green_mg:1200000,expected_mg:1000000},{id:'p1',status:'planned',coffee:'Coffee',roast_at:past,green_mg:1200000,expected_mg:1000000}],demands:[],coffees:[],stocks:[],green:{beans:[]}};
let html=planPage(viewS,h);
assert(html.includes('commitment-header status-green'));assert(html.includes('commitment-header status-red'));
assert(html.includes('data-action="complete-plan"'));assert(html.includes('Why this suggestion?'));
console.log('Order and production colors: deadline boundaries, fulfillment, missing data, coverage, rest, picks, recipes, legacy navigation and rendered headers passed.');
